import Foundation

enum LecturerConfig {
    /// How long the lecturer stands at a spot before walking off.
    static let stayDuration: TimeInterval = 5

    /// How long the walk to the next spot takes, whatever the distance.
    static let moveDuration: TimeInterval = 5
}
